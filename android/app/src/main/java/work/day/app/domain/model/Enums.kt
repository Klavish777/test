package work.day.app.domain.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/** Целевые площадки. Приложения-агенты работают синхронно на обеих. */
@Serializable
enum class Platform(val label: String, val short: String, val studioName: String) {
    @SerialName("youtube") YOUTUBE("YouTube", "YT", "YouTube Studio"),
    @SerialName("tiktok") TIKTOK("TikTok", "TT", "TikTok Studio"),
}

/** Уровень автономии агента. Публикация без человека невозможна принципиально — см. Risk.HIGH. */
@Serializable
enum class Autonomy(val label: String, val description: String) {
    @SerialName("advise") ADVISE("Советник", "Только план и рекомендации. Ничего не готовит к публикации."),
    @SerialName("prepare") PREPARE("Исполнитель", "Готовит пакеты (тексты, ТЗ, графики) и ждёт твоего одобрения."),
    @SerialName("schedule") SCHEDULE("Планировщик", "Сам ставит готовые пакеты в очередь публикации по слотам."),
}

/** Статус задачи агента в течение смены. */
@Serializable
enum class TaskStatus(val label: String) {
    @SerialName("planned") PLANNED("В плане"),
    @SerialName("running") RUNNING("Выполняется"),
    @SerialName("needs_approval") NEEDS_APPROVAL("Ждёт одобрения"),
    @SerialName("queued") QUEUED("В очереди публикации"),
    @SerialName("done") DONE("Готово"),
    @SerialName("skipped") SKIPPED("Пропущено"),
    @SerialName("failed") FAILED("Ошибка"),
}

/** Насколько действие заметно наружу. HIGH всегда остаётся ручным. */
@Serializable
enum class Risk(val label: String, val note: String) {
    @SerialName("low") LOW("Низкий", "Внутренняя работа: аналитика, черновики, планы."),
    @SerialName("medium") MEDIUM("Средний", "Тексты и материалы, которые ты публикуешь сам."),
    @SerialName("high") HIGH("Высокий", "Касается публичной страницы канала — только руками человека."),
}

@Serializable
enum class EventKind(val label: String) {
    @SerialName("shift_start") SHIFT_START("Смена началась"),
    @SerialName("plan") PLAN("Планирование"),
    @SerialName("start") START("Взял задачу"),
    @SerialName("output") OUTPUT("Материал готов"),
    @SerialName("need_approval") NEED_APPROVAL("Нужно одобрение"),
    @SerialName("done") DONE("Закрыто"),
    @SerialName("skip") SKIP("Пропуск"),
    @SerialName("warning") WARNING("Внимание"),
    @SerialName("shift_end") SHIFT_END("Смена закрыта"),
    @SerialName("info") INFO("Служебное"),
}

