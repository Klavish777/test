/**
 * Офлайн-движок. Работает без сети и без ключа: по шаблону каждого TaskKind собирает
 * черновик материала из контекста канала. Это не замена модели, а честный fallback —
 * приложение остаётся полезным в самолёте и позволяет посмотреть интерфейс без API.
 * Все тексты помечены source = OFFLINE, чтобы их не путали с генерацией модели.
 */
class OfflineLlm : LlmClient {

    override val source = LlmClient.Source.OFFLINE

    override suspend fun complete(brief: LlmBrief): LlmResult {
        val kind = Templates.detect(brief.user)
        return LlmResult(
            text = Templates.render(kind, brief.user),
            source = source,
        )
    }

}

