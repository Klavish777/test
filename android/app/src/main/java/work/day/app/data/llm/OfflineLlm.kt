            appendLine("Черновик от офлайн-движка. Подключи модель в настройках — текст станет точнее.")
            appendLine()
            appendLine("Задача: ${kind.title} · ниша: $niche")
            appendLine()
            appendLine("Что сделано по шаблону «${kind.deliverable}»:")
            lines(kind, niche, cadence, tone, rng).forEach { appendLine(it) }
            appendLine()
            appendLine("Проверка результата: ${kind.metric}. Смотри через 7 дней, не раньше.")
            appendLine("Ограничение: накрутка не используется — только органика и ручная публикация.")
        }.trim()
    }

